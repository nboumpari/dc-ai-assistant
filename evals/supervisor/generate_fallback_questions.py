"""Generate the extra fallback questions for the router evaluation.

Run once from the project root:

    uv run python -m evals.supervisor.generate_fallback_questions

Why: the two agents' golden sets together hold only 3 questions the router
should send to the fallback (2 dev, 1 test), too few to measure it. This adds
a small set for the router evaluation only; the agents' golden sets are not
changed. Writes evals/supervisor/golden_set.yaml, which a person reviews
before use. Every question is marked source: added_for_router.

Two kinds, both expected to go to the fallback:
  conversation  greetings, thanks, questions about what the assistant can do, unclear messages
  off_topic     subjects unrelated to warehousing and transport
"""

import random
import sys
from pathlib import Path

import yaml

from evals.rules.generate_golden_set import NOT_FOUND_SCHEMA, ask_json, too_similar
from evals.rules.generate_golden_set import _client as openai_client

OUT_PATH = Path(__file__).with_name("golden_set.yaml")
DATA_GOLDEN = Path(__file__).parents[1] / "golden_set.yaml"
RULES_GOLDEN = Path(__file__).parents[1] / "rules" / "golden_set.yaml"
KINDS = {  # kind: (how many, dev share)
    "conversation": (4, 3),
    "off_topic": (6, 4),
}
SEED = 42

PROMPTS = {
    "conversation": (
        "A company's control tower assistant answers warehouse operations data questions and questions about "
        "logistics rules and standards. Write {n} short, realistic messages a warehouse planner might type that "
        "are not questions for either. Cycle through these kinds in this order, one message each: a greeting; "
        "thanks; a question about what the assistant can do or how to use it; an unclear message that cannot be "
        "answered without more context and does not name any warehouse topic."
    ),
    "off_topic": (
        "A company's control tower assistant answers warehouse operations data questions and questions about "
        "logistics rules and standards. Write {n} short, realistic questions an employee might type into it that "
        "have nothing to do with warehousing, transport or logistics (for example cooking, sport, travel, health, "
        "coding, entertainment, HR or personal finance). Vary the topics; one question each."
    ),
}

HEADER = (
    "# Extra questions for the supervisor's router evaluation (route: fallback).\n"
    "# Added because the two agents' golden sets together held only 3 fallback questions (2 dev, 1 test).\n"
    "# Generated by evals/supervisor/generate_fallback_questions.py (gpt-5.5), then reviewed by a person.\n"
    "# Used by the router evaluation only; the agents' golden sets are unchanged.\n\n"
)


def existing_questions() -> list[str]:
    data = yaml.safe_load(DATA_GOLDEN.read_text(encoding="utf-8"))
    data = data["questions"] if isinstance(data, dict) else data
    rules = yaml.safe_load(RULES_GOLDEN.read_text(encoding="utf-8"))["questions"]
    return [q["question"] for q in data + rules]


def main() -> int:
    client = openai_client()
    rng = random.Random(SEED)
    seen = existing_questions()
    questions = []
    for kind, (n, n_dev) in KINDS.items():
        candidates = ask_json(client, PROMPTS[kind].format(n=n * 2), NOT_FOUND_SCHEMA, f"fallback_{kind}")["questions"]
        if kind == "conversation":  # the model cycles through the kinds, so keep the first message of each
            candidates = [candidates[i] for i in range(n) if i < len(candidates)] + candidates[n:]
        chosen = []
        for text in candidates:
            if len(chosen) < n and not too_similar(text, seen + chosen):
                chosen.append(text)
        rng.shuffle(chosen)
        for i, text in enumerate(chosen):
            split = "dev" if i < n_dev else "test"
            questions.append({"question": text, "kind": kind, "split": split})
            print(f"  {kind:12} {split:4} {text}")
    out = [
        {"id": f"F{i:02d}", **q, "route": "fallback", "behavior": "fallback", "source": "added_for_router"}
        for i, q in enumerate(questions, start=1)
    ]
    OUT_PATH.write_text(
        HEADER + yaml.safe_dump({"questions": out}, sort_keys=False, allow_unicode=True, width=110), encoding="utf-8"
    )
    print(f"\nWrote {len(out)} questions to {OUT_PATH.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
